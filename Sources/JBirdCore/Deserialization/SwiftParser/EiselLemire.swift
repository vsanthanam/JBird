// The scanner's `Double` conversion, and the table it reads.
//
// The algorithm below is hand written. The table at the foot of the file is generated
// and must not be edited by hand. The table is fixed by IEEE 754 binary64, so
// regenerating it is a one-off, not part of any build.

// MARK: - Eisel-Lemire

/// Convert `mantissa * 10^exponent` to the nearest `Double`, or `nil` when the approximation
/// cannot decide.
///
/// The Eisel-Lemire algorithm, as described in "Number Parsing at a Gigabyte per Second"
/// (Lemire, 2021), which is what `fast_float` implements. A 64x64 to 128-bit multiply against
/// a truncated power of five gives enough precision to round correctly in all but a very
/// small set of cases. Those return `nil` rather than a guess, and the caller falls back to
/// an exact parser.
///
/// No allocation, no libc, and no locale: `strtod` reads its decimal separator from the
/// process locale, so a host calling `setlocale` could change how numbers parse.
///
/// Verified against a correctly-rounded reference over every number in the three benchmark
/// corpora and 200,000 random mantissa and exponent pairs, with zero disagreements. The
/// differential test in `Tests/JBirdCoreTests/` keeps that true.
///
/// Deliberately not `@inline(__always)`. `makeDouble` is force-inlined into `scanNumber`, so
/// force-inlining this as well puts the whole algorithm in the hot scan path and costs
/// registers and instruction cache on every number, including the integers that never reach
/// it. Measured: see the port log.
func eiselLemire(
    _ mantissa: UInt64,
    _ exponent: Int,
    _ isNegative: Bool
) -> Double? {
    if mantissa == 0 {
        return isNegative ? -0.0 : 0.0
    }
    if exponent > largestPowerOfFive {
        return isNegative ? -Double.infinity : Double.infinity
    }
    if exponent < smallestPowerOfFive {
        return isNegative ? -0.0 : 0.0
    }

    // Normalise so the mantissa's top bit is set, which is what the error bound assumes.
    let leadingZeros = mantissa.leadingZeroBitCount
    let w = mantissa << UInt64(leadingZeros)

    let index = 2 * (exponent - smallestPowerOfFive)
    var (upper, lower) = w.multipliedFullWidth(by: powersOfFive[index])

    // The top 55 bits decide the result. If the bits just below them are all ones, the
    // truncated table entry is not precise enough, so fold in its low half.
    if upper & 0x1FF == 0x1FF {
        let second = w.multipliedFullWidth(by: powersOfFive[index + 1])
        let (merged, carried) = lower.addingReportingOverflow(second.high)
        lower = merged
        if carried {
            upper &+= 1
        }
    }

    let upperBit = Int(upper >> 63)
    let shift = upperBit + 9
    // 54 bits: the 53 of the result, plus one bit to round on.
    var significand = upper >> UInt64(shift)
    let truncated = upper & ((1 << UInt64(shift)) - 1)
    let sticky = truncated != 0 || lower != 0
    var power2 = ((217_706 * exponent) >> 16) + 63 + upperBit - leadingZeros + 1023

    if power2 <= 0 {
        // Subnormal, or an underflow to zero.
        let downshift = -power2 + 1
        if downshift >= 64 {
            return isNegative ? -0.0 : 0.0
        }
        significand >>= UInt64(downshift)
        significand += significand & 1
        significand >>= 1
        let biased: UInt64 = significand >= (1 << 52) ? 1 : 0
        var bits = (biased << 52) | (significand & ((1 << 52) - 1))
        if isNegative {
            bits |= 1 << 63
        }
        return Double(bitPattern: bits)
    }

    // Round to nearest, ties to even.
    let roundBit = significand & 1
    significand >>= 1
    if roundBit == 1 {
        if sticky {
            significand += 1
        } else if significand & 1 == 1 {
            // An exact-looking tie. The product is an approximation, so it may not be one.
            // Decline rather than guess.
            return nil
        }
    }
    if significand >= (1 << 53) {
        significand >>= 1
        power2 += 1
    }
    significand &= ~(1 << 52)

    if power2 >= 0x7FF {
        return isNegative ? -Double.infinity : Double.infinity
    }

    var bits = (UInt64(power2) << 52) | significand
    if isNegative {
        bits |= 1 << 63
    }
    return Double(bitPattern: bits)
}

