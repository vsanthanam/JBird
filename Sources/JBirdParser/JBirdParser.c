static bool json_has_more(json_parser_t *parser) {
    return parser->index < parser->length;
}

static uint8_t json_peek(json_parser_t *parser) {
    if (parser->index >= parser->length) {
        return 0;
    }
    return parser->input[parser->index];
}

static uint8_t json_next(json_parser_t *parser) {
    if (parser->index >= parser->length) {
        return 0;
    }
    return parser->input[parser->index++];
}

static __attribute__((noinline)) size_t json_consume_long_whitespace(const uint8_t *input, size_t index, size_t length) {
    index = json_skip_whitespace_bytes(input, index, length);

    while (index < length && is_whitespace(input[index])) {
        index++;
    }

    return index;
}

static inline __attribute__((always_inline)) void json_consume_whitespace(json_parser_t *parser) {
    if (parser->require_minified) {
        return;
    }

    const uint8_t *input = parser->input;
    size_t length = parser->length;
    size_t index = parser->index;

    if (index >= length || !is_whitespace(input[index])) {
        return;
    }

    index++;

    if (index < length && is_whitespace(input[index])) {
        index = json_consume_long_whitespace(input, index + 1, length);
    }

    parser->index = index;
}

static void json_parse_bom(json_parser_t *parser) {
    if (parser->length >= 3 &&
        parser->input[0] == 0xEF &&
        parser->input[1] == 0xBB &&
        parser->input[2] == 0xBF) {
        parser->index = 3;
    }
}

static json_error_t json_expect(json_parser_t *parser, uint8_t expected) {
    if (!json_has_more(parser)) {
        return JSON_UNEXPECTED_END_OF_INPUT;
    }

    uint8_t c = json_next(parser);
    if (c != expected) {
        return JSON_INVALID_CHARACTER;
    }

    return JSON_NO_ERROR;
}

static json_error_t json_parse_hex(json_parser_t *parser, uint16_t *out_value) {
    if (!json_has_more(parser)) {
        return JSON_UNEXPECTED_END_OF_INPUT;
    }

    uint8_t c = json_next(parser);
    uint16_t value = 0;

    if (c >= '0' && c <= '9') {
        value = c - '0';
    } else if (c >= 'a' && c <= 'f') {
        value = 10 + (c - 'a');
    } else if (c >= 'A' && c <= 'F') {
        value = 10 + (c - 'A');
    } else {
        return JSON_INVALID_UNICODE;
    }

    *out_value = value;
    return JSON_NO_ERROR;
}

static json_error_t json_parse_hex_sequence(json_parser_t *parser, uint16_t *out_value) {
    uint16_t h1, h2, h3, h4;
    json_error_t err;

    if ((err = json_parse_hex(parser, &h1)) != JSON_NO_ERROR)
        return err;
    if ((err = json_parse_hex(parser, &h2)) != JSON_NO_ERROR)
        return err;
    if ((err = json_parse_hex(parser, &h3)) != JSON_NO_ERROR)
        return err;
    if ((err = json_parse_hex(parser, &h4)) != JSON_NO_ERROR)
        return err;

    *out_value = (h1 << 12) | (h2 << 8) | (h3 << 4) | h4;
    return JSON_NO_ERROR;
}

static json_error_t json_add_codepoint(json_parser_t *parser, uint32_t codepoint) {
    json_error_t err;

    if (codepoint <= 0x7F) {
        err = json_temp_buffer_append_byte(parser, (char)codepoint);
    } else if (codepoint <= 0x7FF) {
        err = json_temp_buffer_append_byte(parser, (char)(0xC0 | (codepoint >> 6)));
        if (err == JSON_NO_ERROR) {
            err = json_temp_buffer_append_byte(parser, (char)(0x80 | (codepoint & 0x3F)));
        }
    } else if (codepoint <= 0xFFFF) {
        err = json_temp_buffer_append_byte(parser, (char)(0xE0 | (codepoint >> 12)));
        if (err == JSON_NO_ERROR) {
            err = json_temp_buffer_append_byte(parser, (char)(0x80 | ((codepoint >> 6) & 0x3F)));
        }
        if (err == JSON_NO_ERROR) {
            err = json_temp_buffer_append_byte(parser, (char)(0x80 | (codepoint & 0x3F)));
        }
    } else if (codepoint <= 0x10FFFF) {
        err = json_temp_buffer_append_byte(parser, (char)(0xF0 | (codepoint >> 18)));
        if (err == JSON_NO_ERROR) {
            err = json_temp_buffer_append_byte(parser, (char)(0x80 | ((codepoint >> 12) & 0x3F)));
        }
        if (err == JSON_NO_ERROR) {
            err = json_temp_buffer_append_byte(parser, (char)(0x80 | ((codepoint >> 6) & 0x3F)));
        }
        if (err == JSON_NO_ERROR) {
            err = json_temp_buffer_append_byte(parser, (char)(0x80 | (codepoint & 0x3F)));
        }
    } else {
        return JSON_INVALID_UNICODE;
    }

    return err;
}

static json_error_t json_parse_string_into_temp_buffer(json_parser_t *parser) {
    json_error_t err;
    size_t estimate_size = 128;
    size_t remaining = parser->length - parser->index;
    if (remaining > 1)
        estimate_size = (remaining < 1024) ? remaining : 1024;

    err = json_temp_buffer_ensure_capacity(parser, estimate_size);
    if (err != JSON_NO_ERROR)
        return err;
    json_temp_buffer_clear(parser);

    bool escape_mode = false;
    while (json_has_more(parser)) {
        uint8_t c = json_next(parser);

        if (escape_mode) {
            escape_mode = false;
            switch (c) {
            case '"':
            case '\\':
            case '/':
                err = json_temp_buffer_append_byte(parser, c);
                break;
            case 'b':
                err = json_temp_buffer_append_byte(parser, '\b');
                break;
            case 'f':
                err = json_temp_buffer_append_byte(parser, '\f');
                break;
            case 'n':
                err = json_temp_buffer_append_byte(parser, '\n');
                break;
            case 'r':
                err = json_temp_buffer_append_byte(parser, '\r');
                break;
            case 't':
                err = json_temp_buffer_append_byte(parser, '\t');
                break;
            case 'u': {
                uint16_t code_unit1, code_unit2;
                err = json_parse_hex_sequence(parser, &code_unit1);
                if (err != JSON_NO_ERROR)
                    return err;

                if (code_unit1 >= 0xD800 && code_unit1 <= 0xDBFF) {
                    if (!(json_has_more(parser) && json_next(parser) == '\\' &&
                          json_has_more(parser) && json_next(parser) == 'u'))
                        return JSON_INVALID_UNICODE;
                    err = json_parse_hex_sequence(parser, &code_unit2);
                    if (err != JSON_NO_ERROR)
                        return err;
                    if (code_unit2 < 0xDC00 || code_unit2 > 0xDFFF)
                        return JSON_INVALID_UNICODE;
                    uint32_t codepoint = 0x10000 + (((code_unit1 & 0x3FF) << 10) | (code_unit2 & 0x3FF));
                    err = json_add_codepoint(parser, codepoint);
                } else if (code_unit1 >= 0xDC00 && code_unit1 <= 0xDFFF) { // Low surrogate without high
                    return JSON_INVALID_UNICODE;
                } else { // BMP
                    err = json_add_codepoint(parser, code_unit1);
                }
                break;
            }
            default:
                return JSON_INVALID_ESCAPE;
            }
            if (err != JSON_NO_ERROR)
                return err;
        } else if (c == '"') {
            return JSON_NO_ERROR;
        } else if (c == '\\') {
            escape_mode = true;
        } else if (c < 0x20) {
            return JSON_INVALID_STRING;
        } else {
            err = json_temp_buffer_append_byte(parser, c);
            if (err != JSON_NO_ERROR)
                return err;
        }
    }
    return JSON_UNEXPECTED_END_OF_INPUT;
}

// MARK: - Number Parsing
//
// Numbers are parsed in two stages. The scanner reads the decimal digits into an
// exact 64-bit mantissa (at most 19 significant digits) and a base-10 exponent.
// The conversion stage then rounds that exact decimal to the nearest double
// exactly once, so results match `strtod` and Foundation bit for bit:
//
//   1. Clinger's fast path when the mantissa fits in 53 bits and the power of
//      ten is exactly representable, which covers most real-world numbers.
//   2. The Eisel-Lemire algorithm, which is exact for any mantissa below 2^64
//      and any decimal exponent in the range of double.
//   3. `strtod` only when the input has more than 19 significant digits and the
//      two Eisel-Lemire candidates disagree on the rounding.

// Mantissa values below this can accept one more decimal digit without
// exceeding 19 digits, which is guaranteed to fit in a uint64_t.
#define JSON_MANTISSA_LIMIT 1000000000000000000ULL

// Mantissas up to 2^53 are exactly representable as a double.
#define JSON_CLINGER_MAX_MANTISSA (1ULL << 53)

// Exponents beyond this magnitude are clamped while scanning. Any exponent this
// large already produces zero or infinity regardless of the mantissa.
#define JSON_EXPONENT_CLAMP 100000

static const uint64_t pow10_u64_table[20] = {
    1ULL,
    10ULL,
    100ULL,
    1000ULL,
    10000ULL,
    100000ULL,
    1000000ULL,
    10000000ULL,
    100000000ULL,
    1000000000ULL,
    10000000000ULL,
    100000000000ULL,
    1000000000000ULL,
    10000000000000ULL,
    100000000000000ULL,
    1000000000000000ULL,
    10000000000000000ULL,
    100000000000000000ULL,
    1000000000000000000ULL,
    10000000000000000000ULL};

typedef struct {
    uint64_t high;
    uint64_t low;
} json_uint128_t;

static inline json_uint128_t json_full_multiply(uint64_t a, uint64_t b) {
    json_uint128_t result;
#if defined(__SIZEOF_INT128__)
    __uint128_t product = (__uint128_t)a * (__uint128_t)b;
    result.high = (uint64_t)(product >> 64);
    result.low = (uint64_t)product;
#else
    uint64_t a_low = (uint32_t)a;
    uint64_t a_high = a >> 32;
    uint64_t b_low = (uint32_t)b;
    uint64_t b_high = b >> 32;
    uint64_t p0 = a_low * b_low;
    uint64_t p1 = a_low * b_high;
    uint64_t p2 = a_high * b_low;
    uint64_t p3 = a_high * b_high;
    uint64_t middle = p2 + (p0 >> 32) + (uint32_t)p1;
    result.high = p3 + (middle >> 32) + (p1 >> 32);
    result.low = (middle << 32) | (uint32_t)p0;
#endif
    return result;
}

static inline int json_leading_zeros(uint64_t value) {
#if defined(__GNUC__) || defined(__clang__)
    return __builtin_clzll(value);
#else
    int count = 0;
    while ((value & (1ULL << 63)) == 0) {
        value <<= 1;
        count++;
    }
    return count;
#endif
}

static inline double json_double_from_bits(uint64_t bits) {
    double value;
    memcpy(&value, &bits, sizeof(value));
    return value;
}

// Computes the double nearest to mantissa * 10^exponent using the Eisel-Lemire
// algorithm. Requires mantissa != 0 and exponent within
// [JSON_SMALLEST_POWER_OF_TEN, JSON_LARGEST_POWER_OF_TEN]. This follows the
// reference implementation in fast_float, including the proof by Mushtak and
// Lemire that the truncated 128-bit product is always accurate enough.
static double json_eisel_lemire(uint64_t mantissa, int64_t exponent) {
    int leading_zeros = json_leading_zeros(mantissa);
    uint64_t w = mantissa << leading_zeros;

    const uint64_t *power = json_powers_of_five_128[exponent - JSON_SMALLEST_POWER_OF_TEN];
    json_uint128_t product = json_full_multiply(w, power[0]);

    // The top 55 bits of the product are exact unless the 9 bits below them are
    // all ones, in which case the next 64 bits of the power are folded in.
    if ((product.high & 0x1FF) == 0x1FF) {
        json_uint128_t second = json_full_multiply(w, power[1]);
        product.low += second.high;
        if (second.high > product.low) {
            product.high++;
        }
    }

    uint64_t upper_bit = product.high >> 63;
    int shift = (int)upper_bit + 9;
    uint64_t binary_mantissa = product.high >> shift;

    // floor(log2(10^exponent)) + 63, then rebased against the double exponent bias.
    int64_t power2 = ((217706 * exponent) >> 16) + 63 + (int64_t)upper_bit - leading_zeros + 1023;

    if (power2 <= 0) {
        // Subnormal or zero.
        if (-power2 + 1 >= 64) {
            return 0.0;
        }
        binary_mantissa >>= -power2 + 1;
        binary_mantissa += (binary_mantissa & 1);
        binary_mantissa >>= 1;
        // Rounding may have carried into the smallest normal.
        power2 = (binary_mantissa < (1ULL << 52)) ? 0 : 1;
        return json_double_from_bits(binary_mantissa | ((uint64_t)power2 << 52));
    }

    // Halfway cases between two doubles must round to even. They can only occur
    // when 5^exponent fits in 64 bits and the discarded product bits were zero.
    if (product.low <= 1 && exponent >= -4 && exponent <= 23 && (binary_mantissa & 3) == 1) {
        if ((binary_mantissa << shift) == product.high) {
            binary_mantissa &= ~1ULL;
        }
    }

    binary_mantissa += (binary_mantissa & 1);
    binary_mantissa >>= 1;

    if (binary_mantissa >= (2ULL << 52)) {
        binary_mantissa = 1ULL << 52;
        power2++;
    }
    binary_mantissa &= ~(1ULL << 52);

    if (power2 >= 2047) {
        return INFINITY;
    }

    return json_double_from_bits(binary_mantissa | ((uint64_t)power2 << 52));
}

// Converts the unsigned decimal text using the C library. Only reached for
// inputs with more than 19 significant digits whose rounding Eisel-Lemire
// could not settle. `fallback` is returned if the text cannot be converted.
static double json_strtod_fallback(const uint8_t *text, size_t length, double fallback) {
    char stack_buffer[128];
    char *buffer = stack_buffer;
    if (length + 1 > sizeof(stack_buffer)) {
        buffer = malloc(length + 1);
        if (!buffer) {
            return fallback;
        }
    }
    memcpy(buffer, text, length);
    buffer[length] = '\0';

    char *end = NULL;
    double value = strtod(buffer, &end);

    if (end != buffer + length) {
        // The C locale may use a decimal separator other than '.'.
        struct lconv *locale = localeconv();
        char *dot = memchr(buffer, '.', length);
        if (locale && locale->decimal_point && locale->decimal_point[0] != '\0' && locale->decimal_point[1] == '\0' && dot) {
            *dot = locale->decimal_point[0];
            value = strtod(buffer, &end);
        }
        if (end != buffer + length) {
            value = fallback;
        }
    }

    if (buffer != stack_buffer) {
        free(buffer);
    }
    return value;
}

// Rounds mantissa * 10^exponent to the nearest double exactly once. `truncated`
// indicates that the input had more than 19 significant digits and the dropped
// digits were not all zero; `text` and `text_length` cover the unsigned number
// text for the rare cases that need the C library.
static double json_decimal_to_double(uint64_t mantissa, int64_t exponent, bool truncated, const uint8_t *text, size_t text_length) {
    if (mantissa == 0) {
        return 0.0;
    }

    if (!truncated && mantissa <= JSON_CLINGER_MAX_MANTISSA) {
        // Clinger's fast path: both operands are exact, so one IEEE operation
        // produces the correctly rounded result.
        if (exponent >= -22 && exponent <= 22) {
            double value = (double)mantissa;
            return exponent < 0 ? value / pow10_table[-exponent] : value * pow10_table[exponent];
        }
        // Extended fast path: fold part of the exponent into the mantissa while
        // it still fits in 53 bits.
        if (exponent > 22 && exponent <= 22 + 19) {
            uint64_t scale = pow10_u64_table[exponent - 22];
            if (mantissa <= JSON_CLINGER_MAX_MANTISSA / scale) {
                return (double)(mantissa * scale) * pow10_table[22];
            }
        }
    }

    // mantissa < 10^19 < 2^64, so any smaller exponent rounds to zero.
    if (exponent < JSON_SMALLEST_POWER_OF_TEN) {
        return 0.0;
    }
    // mantissa >= 1, so any larger exponent overflows.
    if (exponent > JSON_LARGEST_POWER_OF_TEN) {
        return INFINITY;
    }

    double value = json_eisel_lemire(mantissa, exponent);
    if (truncated) {
        // The true value lies strictly between mantissa and mantissa + 1 at this
        // exponent. If both round to the same double, so does the true value.
        double upper = json_eisel_lemire(mantissa + 1, exponent);
        if (value != upper) {
            value = json_strtod_fallback(text, text_length, value);
        }
    }
    return value;
}

static json_error_t json_parse_number(json_parser_t *parser, json_value_t **out_value) {
    const uint8_t *const input = parser->input;
    const uint8_t *const end = input + parser->length;
    const uint8_t *p = input + parser->index;

    bool is_negative = false;
    if (p < end && *p == '-') {
        is_negative = true;
        p++;
    }

    if (p >= end || (uint8_t)(*p - '0') > 9) {
        return JSON_INVALID_NUMBER;
    }

    const uint8_t *const digits_start = p;

    uint64_t mantissa = 0;
    int64_t exponent = 0;
    bool truncated = false;
    bool is_double = false;
    uint8_t digit;

    // Integer part. Leading zeros are not permitted, so "0" stands alone.
    if (*p == '0') {
        p++;
        if (p < end && (uint8_t)(*p - '0') <= 9) {
            return JSON_INVALID_NUMBER;
        }
    } else {
        while (p < end && (digit = (uint8_t)(*p - '0')) <= 9) {
            if (mantissa < JSON_MANTISSA_LIMIT) {
                mantissa = mantissa * 10 + digit;
            } else {
                exponent++;
                if (digit != 0) {
                    truncated = true;
                }
            }
            p++;
        }
    }

    // Fraction part.
    if (p < end && *p == '.') {
        is_double = true;
        p++;
        if (p >= end || (uint8_t)(*p - '0') > 9) {
            return JSON_INVALID_NUMBER;
        }
        while (p < end && (digit = (uint8_t)(*p - '0')) <= 9) {
            if (mantissa < JSON_MANTISSA_LIMIT) {
                // Leading zeros keep the mantissa at zero and cost nothing.
                mantissa = mantissa * 10 + digit;
                exponent--;
            } else if (digit != 0) {
                truncated = true;
            }
            p++;
        }
    }

    // Exponent part.
    if (p < end && (*p | 0x20) == 'e') {
        is_double = true;
        p++;
        bool exponent_negative = false;
        if (p < end && (*p == '+' || *p == '-')) {
            exponent_negative = (*p == '-');
            p++;
        }
        if (p >= end || (uint8_t)(*p - '0') > 9) {
            return JSON_INVALID_NUMBER;
        }
        int64_t explicit_exponent = 0;
        while (p < end && (digit = (uint8_t)(*p - '0')) <= 9) {
            if (explicit_exponent < JSON_EXPONENT_CLAMP) {
                explicit_exponent = explicit_exponent * 10 + digit;
            }
            p++;
        }
        exponent += exponent_negative ? -explicit_exponent : explicit_exponent;
    }

    parser->index = (size_t)(p - input);

    // Integers that fit in int64_t stay integers. `exponent` is non-zero here
    // only if integer digits were dropped, which means the value is too large.
    if (!is_double && exponent == 0) {
        uint64_t limit = is_negative ? ((uint64_t)INT64_MAX + 1u) : (uint64_t)INT64_MAX;
        if (mantissa <= limit) {
            int64_t signed_value;
            if (is_negative) {
                signed_value = (mantissa == ((uint64_t)INT64_MAX + 1u)) ? INT64_MIN : -(int64_t)mantissa;
            } else {
                signed_value = (int64_t)mantissa;
            }
            *out_value = json_create_int(parser->arena, signed_value);
            return *out_value ? JSON_NO_ERROR : JSON_OUT_OF_MEMORY;
        }
    }

    double value = json_decimal_to_double(mantissa, exponent, truncated, digits_start, (size_t)(p - digits_start));
    *out_value = json_create_double(parser->arena, is_negative ? -value : value);
    return *out_value ? JSON_NO_ERROR : JSON_OUT_OF_MEMORY;
}
static json_error_t json_parse_value(json_parser_t *parser, json_value_t **out_value);

static json_error_t json_parse_array(json_parser_t *parser, json_value_t **out_value);

static json_error_t json_parse_object(json_parser_t *parser, json_value_t **out_value);

static json_error_t json_parse_true(json_parser_t *parser, json_value_t **out_value);

static json_error_t json_parse_false(json_parser_t *parser, json_value_t **out_value);

static json_error_t json_parse_null(json_parser_t *parser, json_value_t **out_value);

static json_error_t json_parse_value(json_parser_t *parser, json_value_t **out_value) {
    json_consume_whitespace(parser);

    if (!json_has_more(parser)) {
        return JSON_UNEXPECTED_END_OF_INPUT;
    }

    if (parser->max_depth > 0 && parser->current_depth >= parser->max_depth) {
        return JSON_MAX_DEPTH_EXCEEDED;
    }

    uint8_t c = json_peek(parser);
    uint8_t char_type = char_class[c];

    if (char_type == CHAR_CLASS_QUOTE) {
        parser->index++;

        const char *str_start;
        size_t str_length;

        if (json_scan_simple_string(parser, &str_start, &str_length)) {
            json_value_t *value = json_create_value_from_arena(parser->arena);
            if (!value)
                return JSON_OUT_OF_MEMORY;

            value->type = JSON_STRING;
            json_string_init(&value->data.string, str_start, str_length, parser->arena);

            *out_value = value;
            return JSON_NO_ERROR;
        }

        json_error_t err = json_parse_string_into_temp_buffer(parser);
        if (err != JSON_NO_ERROR) {
            return err;
        }

        *out_value = json_create_string(parser->arena, parser->temp_buffer, parser->temp_size);

        json_temp_buffer_clear(parser);

        return *out_value ? JSON_NO_ERROR : JSON_OUT_OF_MEMORY;
    }

    switch (char_type) {
    case CHAR_CLASS_LBRACE:
        return json_parse_object(parser, out_value);

    case CHAR_CLASS_LBRACKET:
        return json_parse_array(parser, out_value);

    case CHAR_CLASS_TRUE_START:
        return json_parse_true(parser, out_value);

    case CHAR_CLASS_FALSE_START:
        return json_parse_false(parser, out_value);

    case CHAR_CLASS_NULL_START:
        return json_parse_null(parser, out_value);

    case CHAR_CLASS_MINUS:
    case CHAR_CLASS_DIGIT:
        return json_parse_number(parser, out_value);

    default:
        return JSON_INVALID_CHARACTER;
    }
}

static json_error_t json_parse_array(json_parser_t *parser, json_value_t **out_value) {
    json_error_t err = json_expect(parser, '[');
    if (err != JSON_NO_ERROR) {
        return err;
    }

    parser->current_depth++;

    json_value_t *array = json_create_array(parser->arena);
    if (!array) {
        return JSON_OUT_OF_MEMORY;
    }

    json_consume_whitespace(parser);

    if (json_has_more(parser) && json_peek(parser) == ']') {
        json_next(parser);
        parser->current_depth--;
        *out_value = array;
        return JSON_NO_ERROR;
    }

    while (1) {
        json_value_t *element = NULL;
        err = json_parse_value(parser, &element);
        if (err != JSON_NO_ERROR) {
            parser->current_depth--;
            return err;
        }

        err = json_array_push(array, element, parser->arena);
        if (err != JSON_NO_ERROR) {
            parser->current_depth--;
            return err;
        }

        json_consume_whitespace(parser);

        if (!json_has_more(parser)) {
            parser->current_depth--;
            return JSON_UNEXPECTED_END_OF_INPUT;
        }

        uint8_t c = json_next(parser);
        if (c == ']') {
            break;
        } else if (c == ',') {
            json_consume_whitespace(parser);
            continue;
        } else {
            parser->current_depth--;
            return JSON_EXPECTED_COMMA_OR_BRACKET;
        }
    }

    parser->current_depth--;
    *out_value = array;
    return JSON_NO_ERROR;
}

static json_error_t json_parse_object(json_parser_t *parser, json_value_t **out_value) {

    json_error_t err = json_expect(parser, '{');
    if (err != JSON_NO_ERROR)
        return err;

    parser->current_depth++;

    json_value_t *object = json_create_object(parser->arena);
    if (!object) {
        parser->current_depth--;
        return JSON_OUT_OF_MEMORY;
    }

    json_consume_whitespace(parser);

    if (json_has_more(parser) && json_peek(parser) == '}') {
        json_next(parser);
        parser->current_depth--;
        *out_value = object;
        return JSON_NO_ERROR;
    }

    while (1) {
        json_consume_whitespace(parser);
        if (!json_has_more(parser) || json_peek(parser) != '"') {
            parser->current_depth--;
            return JSON_MISSING_OBJECT_KEY;
        }

        const char *key;
        size_t key_len;
        uint32_t key_id = 0;
        if (try_parse_simple_string(parser, &key, &key_len)) {
            const char *interned_key = json_string_pool_get_or_add(&parser->arena->string_pool,
                                                                   key, key_len, parser->arena, &key_id);
            if (!interned_key) {
                parser->current_depth--;
                return JSON_OUT_OF_MEMORY;
            }

            if (object->data.object.count >= object->data.object.capacity) {
                size_t new_capacity = object->data.object.capacity * 2;
                if (new_capacity == 0)
                    new_capacity = 8;

                json_key_t *new_keys = (json_key_t *)json_arena_alloc(parser->arena, new_capacity * sizeof(json_key_t));
                struct json_value **new_values = (struct json_value **)json_arena_alloc(parser->arena, new_capacity * sizeof(struct json_value *));

                if (!new_keys || !new_values) {
                    parser->current_depth--;
                    return JSON_OUT_OF_MEMORY;
                }

                if (object->data.object.count > 0) {
                    memcpy(new_keys, object->data.object.keys, object->data.object.count * sizeof(json_key_t));
                    memcpy(new_values, object->data.object.values, object->data.object.count * sizeof(struct json_value *));
                }
                object->data.object.keys = new_keys;
                object->data.object.values = new_values;
                object->data.object.capacity = new_capacity;
            }

            // Check for duplicate keys
            if (parser->strict_keys) {
                for (size_t i = 0; i < object->data.object.count; i++) {
                    const char *existing_key = json_string_get(&object->data.object.keys[i]);
                    size_t existing_len = object->data.object.keys[i].length;

                    if (existing_len == key_len &&
                        memcmp(existing_key, interned_key, key_len) == 0) {
                        parser->current_depth--;
                        return JSON_DUPLICATE_KEY;
                    }
                }
            }

            json_string_t *str = &object->data.object.keys[object->data.object.count];
            str->length = key_len;
            str->pool_id = key_id;

            if (key_len < SMALL_STRING_SIZE) {
                str->is_small = true;
                memcpy(str->data.buf, interned_key, key_len);
                str->data.buf[key_len] = '\0';
            } else {
                str->is_small = false;
                str->data.ptr = (char *)interned_key;
            }
        } else {
            json_next(parser);
            err = json_parse_string_into_temp_buffer(parser);
            if (err != JSON_NO_ERROR) {
                parser->current_depth--;
                return err;
            }

            const char *interned_key = json_string_pool_get_or_add(&parser->arena->string_pool,
                                                                   parser->temp_buffer, parser->temp_size,
                                                                   parser->arena, &key_id);
            if (!interned_key) {
                parser->current_depth--;
                return JSON_OUT_OF_MEMORY;
            }

            if (object->data.object.count >= object->data.object.capacity) {
                size_t new_capacity = object->data.object.capacity * 2;
                if (new_capacity == 0)
                    new_capacity = 8;

                json_key_t *new_keys = (json_key_t *)json_arena_alloc(parser->arena, new_capacity * sizeof(json_key_t));
                struct json_value **new_values = (struct json_value **)json_arena_alloc(parser->arena, new_capacity * sizeof(struct json_value *));

                if (!new_keys || !new_values) {
                    parser->current_depth--;
                    return JSON_OUT_OF_MEMORY;
                }

                if (object->data.object.count > 0) {
                    memcpy(new_keys, object->data.object.keys, object->data.object.count * sizeof(json_key_t));
                    memcpy(new_values, object->data.object.values, object->data.object.count * sizeof(struct json_value *));
                }
                object->data.object.keys = new_keys;
                object->data.object.values = new_values;
                object->data.object.capacity = new_capacity;
            }

            if (parser->strict_keys) {
                for (size_t i = 0; i < object->data.object.count; i++) {
                    const char *existing_key = json_string_get(&object->data.object.keys[i]);
                    size_t existing_len = object->data.object.keys[i].length;

                    if (existing_len == parser->temp_size &&
                        memcmp(existing_key, parser->temp_buffer, parser->temp_size) == 0) {
                        parser->current_depth--;
                        return JSON_DUPLICATE_KEY;
                    }
                }
            }

            json_string_t *str = &object->data.object.keys[object->data.object.count];
            str->length = parser->temp_size;
            str->pool_id = key_id;

            if (parser->temp_size < SMALL_STRING_SIZE) {
                str->is_small = true;
                memcpy(str->data.buf, interned_key, parser->temp_size);
                str->data.buf[parser->temp_size] = '\0';
            } else {
                str->is_small = false;
                str->data.ptr = (char *)interned_key;
            }

            json_temp_buffer_clear(parser);
        }

        json_consume_whitespace(parser);
        if (!json_has_more(parser) || json_next(parser) != ':') {
            parser->current_depth--;
            return JSON_EXPECTED_COLON;
        }
        json_consume_whitespace(parser);

        json_value_t *value = NULL;
        err = json_parse_value(parser, &value);
        if (err != JSON_NO_ERROR) {
            parser->current_depth--;
            return err;
        }

        object->data.object.values[object->data.object.count] = value;

        object->data.object.count++;

        json_consume_whitespace(parser);

        if (!json_has_more(parser)) {
            parser->current_depth--;
            return JSON_UNEXPECTED_END_OF_INPUT;
        }

        uint8_t c = json_next(parser);
        if (c == '}') {
            break;
        } else if (c == ',') {
            json_consume_whitespace(parser);
            continue;
        } else {
            parser->current_depth--;
            return JSON_EXPECTED_COMMA_OR_BRACE;
        }
    }

    parser->current_depth--;
    *out_value = object;
    return JSON_NO_ERROR;
}

static json_error_t json_parse_true(json_parser_t *parser, json_value_t **out_value) {

    if (parser->length - parser->index >= 4 &&
        memcmp(parser->input + parser->index, "true", 4) == 0) {
        parser->index += 4;
        *out_value = json_create_boolean(parser->arena, true);
        return *out_value ? JSON_NO_ERROR : JSON_OUT_OF_MEMORY;
    }

    if (!json_has_more(parser) || json_next(parser) != 't') {
        return JSON_INVALID_LITERAL;
    }

    if (!json_has_more(parser) || json_next(parser) != 'r') {
        return JSON_INVALID_LITERAL;
    }

    if (!json_has_more(parser) || json_next(parser) != 'u') {
        return JSON_INVALID_LITERAL;
    }

    if (!json_has_more(parser) || json_next(parser) != 'e') {
        return JSON_INVALID_LITERAL;
    }

    *out_value = json_create_boolean(parser->arena, true);
    return *out_value ? JSON_NO_ERROR : JSON_OUT_OF_MEMORY;
}

static json_error_t json_parse_false(json_parser_t *parser, json_value_t **out_value) {

    if (parser->length - parser->index >= 5 &&
        memcmp(parser->input + parser->index, "false", 5) == 0) {
        parser->index += 5;
        *out_value = json_create_boolean(parser->arena, false);
        return *out_value ? JSON_NO_ERROR : JSON_OUT_OF_MEMORY;
    }

    if (!json_has_more(parser) || json_next(parser) != 'f') {
        return JSON_INVALID_LITERAL;
    }

    if (!json_has_more(parser) || json_next(parser) != 'a') {
        return JSON_INVALID_LITERAL;
    }

    if (!json_has_more(parser) || json_next(parser) != 'l') {
        return JSON_INVALID_LITERAL;
    }

    if (!json_has_more(parser) || json_next(parser) != 's') {
        return JSON_INVALID_LITERAL;
    }

    if (!json_has_more(parser) || json_next(parser) != 'e') {
        return JSON_INVALID_LITERAL;
    }

    *out_value = json_create_boolean(parser->arena, false);
    return *out_value ? JSON_NO_ERROR : JSON_OUT_OF_MEMORY;
}

static json_error_t json_parse_null(json_parser_t *parser, json_value_t **out_value) {

    if (parser->length - parser->index >= 4 &&
        memcmp(parser->input + parser->index, "null", 4) == 0) {
        parser->index += 4;
        *out_value = json_create_null(parser->arena);
        return *out_value ? JSON_NO_ERROR : JSON_OUT_OF_MEMORY;
    }

    if (!json_has_more(parser) || json_next(parser) != 'n') {
        return JSON_INVALID_LITERAL;
    }

    if (!json_has_more(parser) || json_next(parser) != 'u') {
        return JSON_INVALID_LITERAL;
    }

    if (!json_has_more(parser) || json_next(parser) != 'l') {
        return JSON_INVALID_LITERAL;
    }

    if (!json_has_more(parser) || json_next(parser) != 'l') {
        return JSON_INVALID_LITERAL;
    }

    *out_value = json_create_null(parser->arena);
    return *out_value ? JSON_NO_ERROR : JSON_OUT_OF_MEMORY;
}

static bool try_parse_simple_string(json_parser_t *parser, const char **out_str, size_t *out_len) {
    size_t start_idx = parser->index;
    const uint8_t *input = parser->input;
    size_t length = parser->length;

    if (char_class[input[start_idx]] != CHAR_CLASS_QUOTE)
        return false;
    start_idx++;

    size_t curr_idx = json_skip_plain_string_bytes(input, start_idx, length);
    while (curr_idx < length) {
        uint8_t c = input[curr_idx];

        if (char_class[c] == CHAR_CLASS_QUOTE) {
            *out_str = (const char *)(input + start_idx);
            *out_len = curr_idx - start_idx;
            parser->index = curr_idx + 1;
            return true;
        }

        if (char_class[c] == CHAR_CLASS_BACKSLASH || c < 0x20) {
            return false;
        }

        curr_idx++;
    }

    return false;
}

json_error_t json_parse(const uint8_t *data, size_t length, json_value_t **out_value, bool allow_bom, bool require_minified, bool strict_keys, size_t max_depth) {
    if (!data || !out_value) {
        return JSON_INVALID_JSON;
    }

    *out_value = NULL;

    json_parser_t parser;
    json_parser_init(&parser, data, length, require_minified, strict_keys, max_depth);

    if (!parser.arena) {
        json_parser_cleanup(&parser);
        return JSON_OUT_OF_MEMORY;
    }

    if (allow_bom) {
        json_parse_bom(&parser);
    }

    json_error_t err = json_parse_value(&parser, out_value);

    json_consume_whitespace(&parser);

    if (err == JSON_NO_ERROR && parser.index < parser.length) {
        *out_value = NULL;
        err = JSON_INVALID_JSON;
    }

    free(parser.temp_buffer);
    parser.temp_buffer = NULL;

    if (err != JSON_NO_ERROR) {
        json_arena_free(parser.arena);
        parser.arena = NULL;
        *out_value = NULL;
    }

    return err;
}
